import Foundation
import Network
import os

public enum LoopbackError: Error, Sendable, Equatable {
    /// No loopback port could be bound.
    case bindFailed
    /// The listener was not ready within 5 s.
    case timedOut
}

/// A loopback-only HTTP/1.1 server (127.0.0.1, OS-assigned port) that serves HLS to AVPlayer from files
/// the app is still producing.
///
/// A playlist lists only byte ranges that are already written, so media requests are normally answered
/// at once with a bounded 206 and a real Content-Length, the request shape AVPlayer handles. Requests at
/// the growing edge wait until the producer calls `contentChanged()`.
///
/// Diagnostics: each request leaves one `loop-req` line (path kind, range, status, bytes, milliseconds,
/// open connections and how the send ended) and the listener's changes leave `loop-state` lines, all given
/// to the `log` closure. A request still unanswered after 5 s is reported again every 5 s, with its stage.
/// When a player stalls, the last `loop-req` line is the last thing it asked for and what became of it.
/// `diagnosticLines()` reads the same facts at any moment.
public final class LoopbackServer: Sendable {
    /// How far a request has come.
    private enum Stage: String {
        /// Asked; the answer is not ready (a playlist, or bytes the producer has not written).
        case waiting
        /// Answered; the bytes are on their way to the peer.
        case sending
        case done
    }

    /// One request, from its header to the end of its reply.
    private struct Entry {
        let id: Int
        let connection: Int
        /// playlist, media, data or generated by route; none when no route matched.
        let kind: String
        let path: String
        /// The `Range` header value, without spaces.
        let range: String?
        let started: DispatchTime
        var stage = Stage.waiting
        var status = 0
        var bytes = 0
        var detail: String?
        /// When the answer was ready and its send began.
        var replied: DispatchTime?
        var finished: DispatchTime?
        /// Open connections when it ended.
        var conns: Int?
        /// How it ended: `ok`, `failed:<error>` (the send) or `aborted:<error>` (the connection).
        var sent: String?
    }

    private struct OpenConnection {
        let accepted: DispatchTime
        /// The request that came in on it, once its header is read.
        var request: Int?
    }

    private struct State {
        var listener: NWListener?
        /// The port AVPlayer was given: a listener iOS takes away listens on it again (`lost(_:)`).
        var port: NWEndpoint.Port?
        /// Attempts in a row to listen again after a loss; an accepted connection resets it.
        var relistens = 0
        var isStopped = false
        /// What the listener last reported: setup, waiting, ready, failed, cancelled, lost, dead or stopped.
        var listenerState = "setup"
        /// Connections accepted and not yet closed, by id.
        var connections: [Int: OpenConnection] = [:]
        /// Requests whose send has not ended, by id.
        var pending: [Int: Entry] = [:]
        /// The last requests that ended, oldest first.
        var recent: [Entry] = []
        var nextConnection = 0
        var nextRequest = 0
        var accepted = 0
        /// Replies handed to the network in full.
        var served = 0
        /// Requests whose reply did not reach the peer.
        var aborted = 0
        var lastAccept: DispatchTime?
        var lastRequest: DispatchTime?
    }

    private struct Snapshot {
        var listener: String
        var port: UInt16?
        var conns: Int
        var oldest: DispatchTime?
        var accepted: Int
        var served: Int
        var aborted: Int
        var pending: Int
        var relistens: Int
        var lastAccept: DispatchTime?
        var lastRequest: DispatchTime?
    }

    /// Carries a connection through Network's handler closures without relying on its Sendable conformance.
    private struct Connection: @unchecked Sendable {
        let nw: NWConnection
        let id: Int
    }

    /// Requests kept in `recentRequests()` once they have ended.
    private static let ringCapacity = 16
    /// A request unanswered this long is logged again while it is still pending, up to `slowRounds` times.
    private static let slowAfter = DispatchTimeInterval.seconds(5)
    private static let slowRounds = 6
    /// `relistenLimit` outside tests: about 70 s of trying at the growing pause.
    private static let maxRelistens = 40

    private let routes: [String: LoopbackRoute.Content]
    /// Routes whose path ends in "/", matched by prefix after the exact routes.
    private let prefixRoutes: [(path: String, content: LoopbackRoute.Content)]
    private let waitTimeout: TimeInterval
    private let queue: DispatchQueue
    private let log: (@Sendable (String, [(String, String)]) -> Void)?
    /// Listening attempts in a row after a loss before the server gives up.
    private let relistenLimit: Int
    private let makeListener: @Sendable (NWParameters) throws -> NWListener
    private let changes = ChangeSignal()
    private let state = OSAllocatedUnfairLock(uncheckedState: State())

    /// - Parameters:
    ///   - waitTimeout: how long a request waits for a playlist or for bytes not yet written.
    ///   - log: receives the `loop-req` and `loop-state` lines as a tag and `key=value` fields, the shape
    ///     of the engine's logger events. It runs on server threads and never under the server's lock.
    public convenience init(
        routes: [LoopbackRoute], queueLabel: String = "loopback-hls", waitTimeout: TimeInterval = 15,
        log: (@Sendable (String, [(String, String)]) -> Void)? = nil
    ) {
        self.init(routes: routes, queueLabel: queueLabel, waitTimeout: waitTimeout, log: log,
                  relistenLimit: Self.maxRelistens, makeListener: { try NWListener(using: $0) })
    }

    /// What the public initializer fills in: tests give a shorter `relistenLimit` and a `makeListener` that
    /// fails, to reach the paths a real listener takes only when the system refuses it.
    init(
        routes: [LoopbackRoute], queueLabel: String, waitTimeout: TimeInterval,
        log: (@Sendable (String, [(String, String)]) -> Void)?, relistenLimit: Int,
        makeListener: @escaping @Sendable (NWParameters) throws -> NWListener
    ) {
        var table: [String: LoopbackRoute.Content] = [:]
        for route in routes where !route.path.hasSuffix("/") { table[route.path] = route.content }
        self.routes = table
        prefixRoutes = routes.filter { $0.path.hasSuffix("/") }.map { ($0.path, $0.content) }
        self.waitTimeout = waitTimeout
        self.log = log
        self.relistenLimit = relistenLimit
        self.makeListener = makeListener
        queue = DispatchQueue(label: queueLabel, qos: .userInitiated, attributes: .concurrent)
    }

    /// Starts listening and returns the base URL, `http://127.0.0.1:<port>`, once the listener is ready.
    public func start() async throws -> URL {
        switch await listen(on: .any) {
        case .success(let port):
            return URL(string: "http://127.0.0.1:\(port.rawValue)")!
        case .failure(let failure):
            stop()
            throw failure
        }
    }

    /// Starts a listener on `port` and waits until it is ready: the port it listens on, or why it cannot.
    private func listen(on port: NWEndpoint.Port) async -> Result<NWEndpoint.Port, LoopbackError> {
        // Loopback only: a wildcard bind would let any LAN peer fetch the media without auth.
        let parameters = NWParameters.tcp
        parameters.requiredLocalEndpoint = NWEndpoint.hostPort(host: .ipv4(.loopback), port: port)
        // A lost listener's port is taken again while the connections it accepted may still linger.
        parameters.allowLocalEndpointReuse = true
        guard let listener = try? makeListener(parameters) else {
            emitState("listener-create-failed")
            return .failure(.bindFailed)
        }
        listener.newConnectionHandler = { [weak self] connection in self?.accept(connection) }
        let current = state.withLockUnchecked { state -> Bool in
            guard !state.isStopped else { return false }
            state.listener = listener
            state.listenerState = "setup"
            return true
        }
        guard current else { return .failure(.bindFailed) }
        let listenerQueue = DispatchQueue(label: queue.label + ".listener", qos: .userInitiated)
        let failure: LoopbackError? = await withCheckedContinuation { continuation in
            let resumed = OSAllocatedUnfairLock(initialState: false)
            // True for the call that decides the start, false for every call after it.
            let finish: @Sendable (LoopbackError?) -> Bool = { failure in
                let first = resumed.withLock { resumed in
                    defer { resumed = true }
                    return !resumed
                }
                if first { continuation.resume(returning: failure) }
                return first
            }
            listener.stateUpdateHandler = { [weak self, weak listener] change in
                if let listener { self?.listenerChanged(listener, change) }
                switch change {
                case .ready:
                    _ = finish(nil)
                case .failed, .cancelled:
                    // Once the start is decided, a listener that fails or is cancelled by someone else is lost.
                    if !finish(.bindFailed), let listener { self?.lost(listener) }
                default:
                    break
                }
            }
            listener.start(queue: listenerQueue)
            // Nothing blocks on this, so the limit can outlast the 20 s freezes seen on simulator hosts.
            listenerQueue.asyncAfter(deadline: .now() + 30) { _ = finish(.timedOut) }
        }
        guard failure == nil, let bound = listener.port else {
            // Forget a listener that never came up, so the next attempt starts from nothing.
            state.withLockUnchecked { state in
                if state.listener === listener { state.listener = nil }
            }
            listener.cancel()
            return .failure(failure ?? .bindFailed)
        }
        state.withLockUnchecked { $0.port = bound }
        return .success(bound)
    }

    /// iOS takes a suspended app's listening socket away, and the listener fails once the app runs again
    /// (Apple TN2277). AVPlayer keeps the port in its URLs: a Picture in Picture paused for 2.5 min then
    /// played met "Could not connect to the server" three times and ended (Marquee, 2026-11-20). The server
    /// listens on the same port again, with a growing pause between tries (`relisten(on:)`).
    func lost(_ failed: NWListener) {
        let port = state.withLockUnchecked { state -> NWEndpoint.Port? in
            guard !state.isStopped, state.listener === failed, let port = state.port else { return nil }
            state.listener = nil
            state.listenerState = "lost"
            return port
        }
        failed.cancel()
        guard let port else { return }
        emitState("listener-lost")
        Task { [weak self] in await self?.relisten(on: port) }
    }

    /// Listens on `port` again until it works, the server stops, or `relistenLimit` tries in a row have
    /// failed. Giving up is logged, and shows as `listener=dead`: nothing can connect any more.
    private func relisten(on port: NWEndpoint.Port) async {
        while true {
            let attempt = state.withLockUnchecked { state -> Int in
                guard !state.isStopped, state.listener == nil else { return 0 }
                guard state.relistens < relistenLimit else {
                    state.listenerState = "dead"
                    return -1
                }
                state.relistens += 1
                return state.relistens
            }
            guard attempt != 0 else { return }
            guard attempt > 0 else {
                emitState("listener-gave-up")
                return
            }
            if attempt > 1 { try? await Task.sleep(for: Self.relistenPause(attempt: attempt)) }
            emitState("listener-relisten")
            // A failed attempt leaves no listener behind, so the loop tries again.
            if case .success = await listen(on: port) { return }
        }
    }

    /// The pause before the `attempt`th try in a row: none for the first, then 200 ms more each time up to 2 s.
    static func relistenPause(attempt: Int) -> Duration {
        .milliseconds(min(200 * max(0, attempt - 1), 2000))
    }

    /// The listener now, for tests that stand in for iOS taking it away.
    var currentListener: NWListener? {
        state.withLockUnchecked { $0.listener }
    }

    /// Stops listening and releases waiting requests. Idempotent.
    public func stop() {
        let (listener, first) = state.withLockUnchecked { state -> (NWListener?, Bool) in
            let first = !state.isStopped
            state.isStopped = true
            state.listenerState = "stopped"
            defer { state.listener = nil }
            return (state.listener, first)
        }
        listener?.cancel()
        changes.broadcast()
        if first { emitState("stopped") }
    }

    /// Wakes requests that wait for a playlist or for bytes. Producers call it after each write.
    public func contentChanged() {
        changes.broadcast()
    }

    /// The last 16 requests that ended and every one still unanswered, oldest first, as `loop-req` lines.
    public func recentRequests() -> [String] {
        let now = DispatchTime.now()
        let (entries, conns) = state.withLockUnchecked { state -> ([Entry], Int) in
            let all = state.recent + state.pending.values.sorted { $0.id < $1.id }
            return (Array(all.suffix(Self.ringCapacity)), state.connections.count)
        }
        return entries.map { Self.line("loop-req", Self.fields($0, conns: conns, now: now)) }
    }

    /// The server's state as one `loop-state` line, then one `loop-req` line for each request still
    /// unanswered. What an `EngineDiagnostics.report()` shows of a server that is hung right now.
    public func diagnosticLines() -> [String] {
        let now = DispatchTime.now()
        let (pending, conns) = state.withLockUnchecked { state -> ([Entry], Int) in
            (state.pending.values.sorted { $0.id < $1.id }, state.connections.count)
        }
        return [Self.line("loop-state", stateFields())]
            + pending.map { Self.line("loop-req", Self.fields($0, conns: conns, now: now)) }
    }

    // MARK: - Requests

    private func accept(_ nw: NWConnection) {
        let now = DispatchTime.now()
        let id = state.withLockUnchecked { state -> Int in
            state.nextConnection += 1
            state.accepted += 1
            // It listens, so the losses before it are over.
            state.relistens = 0
            state.lastAccept = now
            state.connections[state.nextConnection] = OpenConnection(accepted: now)
            return state.nextConnection
        }
        nw.stateUpdateHandler = { [weak self, weak nw] change in
            switch change {
            case .failed(let error):
                self?.closed(id, failure: Self.describe(error))
                nw?.cancel()
            case .cancelled:
                self?.closed(id, failure: nil)
            default:
                break
            }
        }
        nw.start(queue: queue)
        receiveHeader(Connection(nw: nw, id: id), buffered: Data())
    }

    /// Reads up to the end of the request header. Request bodies are never needed.
    private func receiveHeader(_ connection: Connection, buffered: Data) {
        connection.nw.receive(minimumIncompleteLength: 1, maximumLength: 16 * 1024) { [weak self] data, _, isComplete, error in
            guard let self else {
                connection.nw.cancel()
                return
            }
            var buffer = buffered
            if let data { buffer.append(data) }
            if let end = buffer.range(of: Data("\r\n\r\n".utf8)) {
                self.respond(connection, header: String(decoding: buffer[..<end.lowerBound], as: UTF8.self))
            } else if error == nil, !isComplete, buffer.count < 64 * 1024 {
                self.receiveHeader(connection, buffered: buffer)
            } else {
                connection.nw.cancel()
            }
        }
    }

    private func respond(_ connection: Connection, header: String) {
        let lines = header.components(separatedBy: "\r\n")
        let requestLine = lines.first?.split(separator: " ") ?? []
        let method = requestLine.first.map { $0.uppercased() } ?? "GET"
        let target = requestLine.count > 1 ? String(requestLine[1]) : "/"
        let path = String(target.prefix { $0 != "?" })
        let range = lines.dropFirst()
            .first { $0.lowercased().hasPrefix("range:") }
            .map { String($0.dropFirst("range:".count)) }
        let client = lines.dropFirst()
            .first { $0.lowercased().hasPrefix("user-agent:") }
            .map { String($0.dropFirst("user-agent:".count)).trimmingCharacters(in: .whitespaces) }
        let content = routes[path] ?? prefixRoutes.first(where: { path.hasPrefix($0.path) })?.content
        let request = begin(connection, path: path, headOnly: method == "HEAD", range: range, client: client,
                            kind: content.map { Self.kind(of: $0) } ?? "none")

        switch content {
        case .playlist(let produce)?:
            servePlaylist(request, produce: produce)
        case .growingFile(let url, let availableBytes, let isComplete, let contentType)?:
            serveGrowingFile(request, url: url, availableBytes: availableBytes, isComplete: isComplete,
                             contentType: contentType)
        case .data(let body, let contentType)?:
            serveData(request, body: body, contentType: contentType)
        case .generated(let make)?:
            whenReady({ make(path) }) { generated in
                guard let generated else {
                    self.reply(request, status: 503, note: "not-ready")
                    return
                }
                self.serveData(request, body: generated.body, contentType: generated.contentType)
            }
        case nil:
            reply(request, status: 404, note: "")
        }
    }

    private struct Request {
        let connection: Connection
        let id: Int
        let path: String
        let headOnly: Bool
        /// The `Range` header value, if any.
        let range: String?
    }

    private func servePlaylist(_ request: Request, produce: @escaping @Sendable () -> String?) {
        whenReady(produce) { text in
            guard let text else {
                self.reply(request, status: 503, note: "not-ready")
                return
            }
            self.reply(request, status: 200, headers: [("Content-Type", "application/vnd.apple.mpegurl"),
                                                       ("Cache-Control", "no-cache")],
                       body: Data(text.utf8), note: Self.summary(ofPlaylist: text))
        }
    }

    private func serveGrowingFile(_ request: Request, url: URL, availableBytes: @escaping @Sendable () -> Int64,
                                  isComplete: @escaping @Sendable () -> Bool, contentType: String) {
        var parsed = ByteRangeRequest.bounded(start: 0, end: nil)
        if let value = request.range {
            guard let range = ByteRangeRequest(header: value) else {
                reply(request, status: 416, note: "bad-range")
                return
            }
            parsed = range
        }
        let wanted = parsed
        // The playlist lists only written ranges, so this normally answers at once; it covers the race at
        // the growing edge.
        whenReady({ () -> Bool? in
            if isComplete() { return true }
            switch wanted {
            case .bounded(let start, let end): return availableBytes() > (end ?? start) ? true : nil
            case .suffix: return nil
            }
        }) { _ in
            // Completion first: a producer records its final size before it reports completion.
            let complete = isComplete()
            let available = availableBytes()
            guard let range = wanted.resolve(available: available, complete: complete) else {
                self.reply(request, status: 416,
                           headers: complete ? [("Content-Range", "bytes */\(available)")] : [],
                           note: "available:\(available)")
                return
            }
            guard let data = Self.read(url, range), !data.isEmpty else {
                self.reply(request, status: 500, note: "read:\(range.lowerBound)-\(range.upperBound)")
                return
            }
            let total = complete ? "\(available)" : "*"
            let last = range.lowerBound + Int64(data.count) - 1
            self.reply(request, status: 206,
                       headers: [("Content-Type", contentType), ("Accept-Ranges", "bytes"),
                                 ("Content-Range", "bytes \(range.lowerBound)-\(last)/\(total)")],
                       body: data)
        }
    }

    private func serveData(_ request: Request, body: Data, contentType: String) {
        guard let value = request.range else {
            reply(request, status: 200, headers: [("Content-Type", contentType)], body: body)
            return
        }
        let total = Int64(body.count)
        guard let range = ByteRangeRequest(header: value)?.resolve(available: total, complete: true) else {
            reply(request, status: 416, headers: [("Content-Range", "bytes */\(total)")], note: "")
            return
        }
        let slice = body.subdata(in: Int(range.lowerBound)..<Int(range.upperBound) + 1)
        reply(request, status: 206,
              headers: [("Content-Type", contentType), ("Accept-Ranges", "bytes"),
                        ("Content-Range", "bytes \(range.lowerBound)-\(range.upperBound)/\(total)")],
              body: slice)
    }

    // MARK: - Helpers

    /// Calls `done` with the probe's value once it has one, re-checking each time a producer reports new
    /// content and at least every 100 ms; with nil once the server stops or `waitTimeout` passes. No thread
    /// blocks meanwhile: a server thread blocked on a lower-QoS producer is a priority inversion, which
    /// Xcode's Thread Performance Checker reports by stalling the process for seconds.
    private func whenReady<T: Sendable>(
        _ probe: @escaping @Sendable () -> T?, deadline: DispatchTime? = nil, _ done: @escaping @Sendable (T?) -> Void
    ) {
        let deadline = deadline ?? DispatchTime.now() + waitTimeout
        let recheck: @Sendable () -> Void = { [queue] in
            queue.async { self.whenReady(probe, deadline: deadline, done) }
        }
        let id = changes.register(recheck)
        if let value = probe() {
            // When a broadcast already took the registration, its re-check answers instead.
            if changes.withdraw(id) { done(value) }
            return
        }
        if state.withLockUnchecked({ $0.isStopped }) || DispatchTime.now() >= deadline {
            if changes.withdraw(id) { done(nil) }
            return
        }
        queue.asyncAfter(deadline: min(deadline, .now() + .milliseconds(100))) { [changes] in
            if changes.withdraw(id) { recheck() }
        }
    }

    /// Registers a request when its header has been read, and starts its watchdog.
    private func begin(_ connection: Connection, path: String, headOnly: Bool, range: String?, client: String?,
                       kind: String) -> Request {
        let now = DispatchTime.now()
        let spaced = range?.trimmingCharacters(in: .whitespaces)
        let (id, isFirst) = state.withLockUnchecked { state -> (Int, Bool) in
            state.nextRequest += 1
            let id = state.nextRequest
            state.pending[id] = Entry(id: id, connection: connection.id, kind: kind, path: path,
                                      range: spaced.map { Self.token($0) }, started: now)
            state.connections[connection.id]?.request = id
            state.lastRequest = now
            return (id, id == 1)
        }
        if log != nil {
            queue.asyncAfter(deadline: .now() + Self.slowAfter) { [weak self] in self?.warn(id, round: 1) }
        }
        // Who asks, once: AVPlayer's loader and anything else on the port look different here.
        if isFirst, let client { emitState("first-request", [("client", Self.token(client))]) }
        return Request(connection: connection, id: id, path: path, headOnly: headOnly, range: range)
    }

    /// Reports a request that has not ended after `slowAfter` while it is still pending, so a hung one is
    /// in the log before anything else happens to it.
    private func warn(_ id: Int, round: Int) {
        let now = DispatchTime.now()
        let slow = state.withLockUnchecked { state -> (entry: Entry, conns: Int)? in
            guard let entry = state.pending[id] else { return nil }
            return (entry, state.connections.count)
        }
        guard let slow else { return }
        emitRequest(slow.entry, conns: slow.conns, now: now)
        if round == 1 { emitState("request-slow") }
        if round < Self.slowRounds {
            queue.asyncAfter(deadline: .now() + Self.slowAfter) { [weak self] in self?.warn(id, round: round + 1) }
        }
    }

    private func reply(_ request: Request, status: Int, headers: [(String, String)] = [],
                       body: Data = Data(), note: String? = nil) {
        let now = DispatchTime.now()
        state.withLockUnchecked { state -> Void in
            guard var entry = state.pending[request.id] else { return }
            entry.stage = .sending
            entry.status = status
            entry.bytes = body.count
            entry.replied = now
            if let note, !note.isEmpty { entry.detail = Self.token(note) }
            state.pending[request.id] = entry
        }

        var head = "HTTP/1.1 \(status) \(Self.reason(status))\r\n"
        for (name, value) in headers { head += "\(name): \(value)\r\n" }
        head += "Content-Length: \(body.count)\r\nConnection: close\r\n\r\n"
        var message = Data(head.utf8)
        if !request.headOnly { message.append(body) }
        let connection = request.connection
        let id = request.id
        // One complete final message, so Network flushes all of it before the cancel; cancelling after a
        // plain send truncates a large body.
        connection.nw.send(content: message, contentContext: .finalMessage, isComplete: true,
                           completion: .contentProcessed { [weak self] error in
                               self?.complete(id, sent: error.map { "failed:" + Self.describe($0) } ?? "ok")
                               connection.nw.cancel()
                           })
    }

    /// Ends a request when its send has finished, once: a connection that closes afterwards changes nothing.
    private func complete(_ id: Int, sent: String) {
        let now = DispatchTime.now()
        let ended = state.withLockUnchecked { state -> (entry: Entry, conns: Int)? in
            guard var entry = state.pending.removeValue(forKey: id) else { return nil }
            entry.stage = .done
            entry.sent = sent
            entry.finished = now
            entry.conns = state.connections.count
            if sent == "ok" { state.served += 1 } else { state.aborted += 1 }
            Self.retire(entry, into: &state)
            return (entry, state.connections.count)
        }
        if let ended { emitRequest(ended.entry, conns: ended.conns, now: now) }
    }

    /// A connection closed: failed with `failure`, or cancelled when it is nil. The request it carried, if its
    /// send has not ended, ends here as aborted.
    private func closed(_ id: Int, failure: String?) {
        let now = DispatchTime.now()
        let ended = state.withLockUnchecked { state -> (entry: Entry, conns: Int)? in
            guard let connection = state.connections.removeValue(forKey: id),
                  let request = connection.request,
                  var entry = state.pending.removeValue(forKey: request) else { return nil }
            entry.stage = .done
            entry.sent = "aborted:" + (failure ?? "closed")
            entry.finished = now
            entry.conns = state.connections.count
            state.aborted += 1
            Self.retire(entry, into: &state)
            return (entry, state.connections.count)
        }
        if let ended { emitRequest(ended.entry, conns: ended.conns, now: now) }
    }

    private static func retire(_ entry: Entry, into state: inout State) {
        state.recent.append(entry)
        if state.recent.count > ringCapacity { state.recent.removeFirst(state.recent.count - ringCapacity) }
    }

    /// Records what the listener reported and logs it. A listener that is no longer the current one (it was
    /// replaced or stopped) is not news.
    private func listenerChanged(_ listener: NWListener, _ change: NWListener.State) {
        let name: String
        var error: NWError?
        switch change {
        case .setup:
            name = "setup"
        case .waiting(let failure):
            name = "waiting"
            error = failure
        case .ready:
            name = "ready"
        case .failed(let failure):
            name = "failed"
            error = failure
        case .cancelled:
            name = "cancelled"
        @unknown default:
            name = "unknown"
        }
        let isCurrent = state.withLockUnchecked { state -> Bool in
            guard state.listener === listener else { return false }
            state.listenerState = name
            return true
        }
        guard isCurrent, name != "setup" else { return }
        var extra: [(String, String)] = []
        if let error { extra.append(("detail", Self.describe(error))) }
        emitState("listener-" + name, extra)
    }

    private func emitRequest(_ entry: Entry, conns: Int, now: DispatchTime) {
        log?("loop-req", Self.fields(entry, conns: conns, now: now))
    }

    private func emitState(_ event: String, _ extra: [(String, String)] = []) {
        guard let log else { return }
        log("loop-state", stateFields(event: event) + extra)
    }

    private func stateFields(event: String? = nil) -> [(String, String)] {
        let now = DispatchTime.now()
        let snapshot = state.withLockUnchecked { state in
            Snapshot(
                listener: state.listenerState, port: state.port?.rawValue, conns: state.connections.count,
                oldest: state.connections.values.map(\.accepted).min(), accepted: state.accepted,
                served: state.served, aborted: state.aborted, pending: state.pending.count,
                relistens: state.relistens, lastAccept: state.lastAccept, lastRequest: state.lastRequest
            )
        }
        func age(_ time: DispatchTime?) -> String {
            time.map { String(Self.milliseconds(from: $0, to: now)) } ?? "-"
        }
        let port = snapshot.port.map { String($0) } ?? "-"
        let descriptors = Self.descriptors()
        var fields: [(String, String)] = []
        if let event { fields.append(("event", event)) }
        fields.append(("listener", snapshot.listener))
        fields.append(("port", port))
        fields.append(("conns", String(snapshot.conns)))
        fields.append(("oldest_conn_ms", age(snapshot.oldest)))
        fields.append(("accepted", String(snapshot.accepted)))
        fields.append(("served", String(snapshot.served)))
        fields.append(("aborted", String(snapshot.aborted)))
        fields.append(("pending", String(snapshot.pending)))
        fields.append(("relistens", String(snapshot.relistens)))
        fields.append(("since_accept_ms", age(snapshot.lastAccept)))
        fields.append(("since_request_ms", age(snapshot.lastRequest)))
        fields.append(("fds", String(descriptors.used)))
        fields.append(("fd_limit", String(descriptors.limit)))
        return fields
    }

    private static func fields(_ entry: Entry, conns: Int, now: DispatchTime) -> [(String, String)] {
        var fields: [(String, String)] = [
            ("id", String(entry.id)), ("conn", String(entry.connection)), ("kind", entry.kind),
            ("path", entry.path), ("range", entry.range ?? "-"),
            ("status", entry.status > 0 ? String(entry.status) : "pending"),
        ]
        if entry.stage != .done { fields.append(("stage", entry.stage.rawValue)) }
        fields += [
            ("bytes", String(entry.bytes)),
            ("ms", String(milliseconds(from: entry.started, to: entry.finished ?? now))),
        ]
        if let replied = entry.replied { fields.append(("ready_ms", String(milliseconds(from: entry.started, to: replied)))) }
        fields.append(("conns", String(entry.conns ?? conns)))
        if let sent = entry.sent { fields.append(("sent", sent)) }
        if let detail = entry.detail { fields.append(("detail", detail)) }
        return fields
    }

    private static func line(_ tag: String, _ fields: [(String, String)]) -> String {
        ([tag] + fields.map { "\($0.0)=\($0.1)" }).joined(separator: " ")
    }

    private static func milliseconds(from start: DispatchTime, to end: DispatchTime) -> Int {
        end.uptimeNanoseconds > start.uptimeNanoseconds ? Int((end.uptimeNanoseconds - start.uptimeNanoseconds) / 1_000_000) : 0
    }

    private static func kind(of content: LoopbackRoute.Content) -> String {
        switch content {
        case .playlist: "playlist"
        case .growingFile: "media"
        case .data: "data"
        case .generated: "generated"
        }
    }

    /// `segs:<listed>,end:<0|1>` for a media playlist: how much of the stream the player was shown, and
    /// whether it was told the stream is over (`#EXT-X-ENDLIST`).
    private static func summary(ofPlaylist text: String) -> String? {
        let segments = text.components(separatedBy: "#EXTINF:").count - 1
        guard segments > 0 else { return nil }
        return "segs:\(segments),end:\(text.contains("#EXT-X-ENDLIST") ? 1 : 0)"
    }

    /// One word for a log line: the first 80 characters, with spaces made underscores.
    private static func token(_ text: String) -> String {
        String(text.prefix(80).map { $0.isWhitespace ? "_" : $0 })
    }

    private static func describe(_ error: NWError) -> String {
        switch error {
        case .posix(let code): "posix-\(code)"
        case .dns(let code): "dns-\(code)"
        case .tls(let status): "tls-\(status)"
        @unknown default: token(String(describing: error))
        }
    }

    /// The process's open file descriptors and its limit on them. A process at the limit cannot accept
    /// a connection, which would leave a request unanswered without any error.
    private static func descriptors() -> (used: Int, limit: Int) {
        var limits = rlimit()
        guard getrlimit(RLIMIT_NOFILE, &limits) == 0 else { return (0, 0) }
        let limit = Int(clamping: limits.rlim_cur)
        var used = 0
        for descriptor in 0..<min(limit, 8192) where fcntl(Int32(descriptor), F_GETFD) != -1 { used += 1 }
        return (used, limit)
    }

    private static func read(_ url: URL, _ range: ClosedRange<Int64>) -> Data? {
        guard let handle = try? FileHandle(forReadingFrom: url) else { return nil }
        defer { try? handle.close() }
        do {
            try handle.seek(toOffset: UInt64(range.lowerBound))
            return try handle.read(upToCount: Int(range.upperBound - range.lowerBound + 1))
        } catch {
            return nil
        }
    }

    private static func reason(_ status: Int) -> String {
        switch status {
        case 200: "OK"
        case 206: "Partial Content"
        case 404: "Not Found"
        case 416: "Range Not Satisfiable"
        case 503: "Service Unavailable"
        default: "Internal Server Error"
        }
    }
}

/// The first range of a `Range: bytes=…` header.
enum ByteRangeRequest: Equatable {
    /// `bytes=a-b` (inclusive) or `bytes=a-`.
    case bounded(start: Int64, end: Int64?)
    /// `bytes=-n`: the last n bytes.
    case suffix(length: Int64)

    init?(header: String) {
        let value = header.trimmingCharacters(in: .whitespaces)
        guard value.lowercased().hasPrefix("bytes=") else { return nil }
        let first = value.dropFirst("bytes=".count).split(separator: ",").first ?? ""
        let bounds = first.split(separator: "-", maxSplits: 1, omittingEmptySubsequences: false)
        guard bounds.count == 2 else { return nil }
        let start = Int64(bounds[0].trimmingCharacters(in: .whitespaces))
        let end = Int64(bounds[1].trimmingCharacters(in: .whitespaces))
        switch (start, end) {
        case (let start?, let end):
            guard start >= 0, (end ?? start) >= start else { return nil }
            self = .bounded(start: start, end: end)
        case (nil, let length?):
            guard length > 0 else { return nil }
            self = .suffix(length: length)
        case (nil, nil):
            return nil
        }
    }

    /// The bytes to send from a resource whose first `available` bytes exist, or nil for 416.
    func resolve(available: Int64, complete: Bool) -> ClosedRange<Int64>? {
        switch self {
        case .bounded(let start, let end):
            guard start < available else { return nil }
            return start...min(end ?? available - 1, available - 1)
        case .suffix(let length):
            guard complete, available > 0 else { return nil }
            return max(0, available - length)...(available - 1)
        }
    }
}
